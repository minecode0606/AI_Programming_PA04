"""Run inference using a fitted RBF-SVM checkpoint produced by grid_search_rbf.py.

Requires activation arrays and extraction_config.json regenerated by extractor.py.
This repository intentionally does not supply nonexistent trained probe weights.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

# Expose the transformer's name under __main__ as well, for joblib files saved
# by the original training script run as `python src/grid_search_rbf.py`.
from grid_search_rbf import (  # noqa: F401
    Config,
    LayerPCAGeometryTransformer,
    preload_last,
)
from lodder import ActivationLoader


def main() -> None:
    parser = argparse.ArgumentParser(description="Predict robust/spurious labels with a saved RBF-SVM model")
    parser.add_argument("--model", default="artifacts/rbf_gridsearch/final_best_model.joblib")
    parser.add_argument("--artifact-dir", default="artifacts/deepseek_r1_qwen3_8b_tat")
    parser.add_argument("--output", default="artifacts/rbf_gridsearch/inference_predictions.csv")
    args = parser.parse_args()

    model_path = Path(args.model)
    if not model_path.is_file():
        parser.error(f"Fitted probe checkpoint not found: {model_path}. Train it with src/grid_search_rbf.py first.")

    loader = ActivationLoader(args.artifact_dir, mmap_mode="r", verify_files=True)
    config = Config(artifact_dir=args.artifact_dir)
    X, sample_ids, _ = preload_last(loader, config)
    model = joblib.load(model_path)  # Load only checkpoints you trust.
    labels = np.asarray(model.predict(X), dtype=np.int64)

    result = pd.DataFrame({"sample_id": sample_ids, "predicted_label": labels})
    if hasattr(model, "decision_function"):
        result["decision_score"] = model.decision_function(X)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    result.to_csv(output, index=False)
    print(f"Wrote {len(result)} predictions to {output}")


if __name__ == "__main__":
    main()
